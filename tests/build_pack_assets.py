"""Rebuild js/quote_assets.js from the customer brochures in AdditionalInfo/Customer brochures.

The quotation pack cover uses each product's brochure cover photo. Images are pulled out of the
PDFs by object number, cropped to the shape they are shown at, and inlined as JPEG data URIs
(the pack window has no base URL, so it can't load files).

Run:  python tests/build_pack_assets.py   (needs PyMuPDF and Pillow)
"""
import base64, io, pathlib
import fitz
from PIL import Image

QT = pathlib.Path(__file__).resolve().parent.parent
BRO = QT / 'AdditionalInfo' / 'Customer brochures'
PDFS = {
    'prsa': 'PRSA_Customer_Brochure_2026.pdf',
    'arf': 'ARF_Customer_Brochure_2026.pdf',
    'ib': 'Allianz Vantage Investment Bond Customer Brochure.pdf',
}
# (image object number, vertical focus 0 = top … 1 = bottom)
COVERS = {'prsa': (799, 0.5), 'arf': (536, 0.5), 'ib': (146, 0.5)}
# Shapes as shown in the pack (mm): photo half of the cover, full-page Bond cover
COVER_HALF = (210, 152)
COVER_FULL = (210, 297)

def grab(doc, xref):
    pix = fitz.Pixmap(doc, xref)
    if pix.n - pix.alpha > 3: pix = fitz.Pixmap(fitz.csRGB, pix)
    if pix.alpha: pix = fitz.Pixmap(pix, 0)
    return Image.open(io.BytesIO(pix.tobytes('png'))).convert('RGB')

def crop(im, shape, focus, width):
    want = shape[0] / shape[1]
    w, h = im.size
    if w / h > want:   # too wide: trim the sides evenly
        nw = round(h * want); x = (w - nw) // 2; im = im.crop((x, 0, x + nw, h))
    else:              # too tall: trim top/bottom around the focus
        nh = round(w / want); y = max(0, min(h - nh, round(focus * h - nh / 2))); im = im.crop((0, y, w, y + nh))
    return im.resize((width, round(width / want)), Image.LANCZOS)

def uri(im, q):
    b = io.BytesIO(); im.save(b, 'JPEG', quality=q, optimize=True, progressive=True)
    return 'data:image/jpeg;base64,' + base64.b64encode(b.getvalue()).decode()

def js_str(s):
    # Break the long base64 strings so the file stays diff- and editor-friendly
    return "'" + '\\\n'.join(s[i:i + 120] for i in range(0, len(s), 120)) + "'"

def main():
    covers = {}
    for prod, fn in PDFS.items():
        doc = fitz.open(str(BRO / fn))
        x, f = COVERS[prod]
        full = prod == 'ib'   # the Bond brochure cover is a full-page photo with the title over the sky
        covers[prod] = uri(crop(grab(doc, x), COVER_FULL if full else COVER_HALF, f, 1240), 68)
    out = [
        '// quote_assets.js — binary assets inlined for the quotation pack. GENERATED by tests/build_pack_assets.py; do not edit by hand.',
        '//',
        '// The pack is written into a new window (or an iframe srcdoc) with no base URL of its own, so any',
        '// image it needs has to travel with it as a data URI rather than a file path.',
        '//',
        '// QT_COVERS: the product brochure covers. PRSA and ARF show the photo across the top of the page;',
        '// the Investment Bond cover is a full-page photo. Products with no entry get the plain navy cover.',
        'var QT_COVERS = {',
        ',\n'.join('  %s: %s' % (k, js_str(v)) for k, v in covers.items()),
        '};',
        '',
    ]
    dest = QT / 'js' / 'quote_assets.js'
    dest.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print('wrote', dest, round(dest.stat().st_size / 1024), 'KB')

if __name__ == '__main__':
    main()
